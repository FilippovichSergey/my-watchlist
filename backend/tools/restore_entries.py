#!/usr/bin/env python3
"""Turns an export of GET /api/entries into SQL that recreates the entry table's contents elsewhere.

Usage: python restore_entries.py entries.json restore.sql
       psql -v ON_ERROR_STOP=1 -f restore.sql "<connection string>"
       (after the application has run its migrations there; keep the options before the connection string,
        the Windows build of psql ignores anything that follows it)

Name the output file as the second argument: the script then writes it itself, as UTF-8 with plain line
feeds. Without it the SQL goes to standard output, which is fine in a pipe but not with ">" in Windows
PowerShell 5.1: that shell re-encodes redirected text to UTF-16, and psql cannot read the result.

The SQL replaces every row, keeps the original ids and timestamps, and resets the id sequence. Used when the
list moves to another database: the migrations recreate the schema and the seed, this brings the owner's
additions, ratings, feedback and Belarusian text.
"""
import json
import sys

NEWLINE = chr(10)
CR = chr(13)
BACKSLASH = chr(92)
COLUMNS = ("id, tmdb_id, media_type, category, title, original_title, release_year, countries, genre_ids, "
           "cast_names, overview, poster_path, tmdb_rating, my_rating, review, title_be, overview_be, created_at")


def lit(value):
    """SQL literal; text with line breaks or backslashes becomes an E-string, so that the file stays one
    statement per line and no CRLF conversion (Windows console, git, editors) can alter the stored text."""
    if value is None:
        return "NULL"
    text = str(value).replace("'", "''")
    if NEWLINE in text or CR in text or BACKSLASH in text:
        # Every character survives: a carriage return travels as an escape too, never dropped
        text = (text.replace(BACKSLASH, BACKSLASH * 2).replace(CR, BACKSLASH + "r")
                .replace(NEWLINE, BACKSLASH + "n"))
        return "E'" + text + "'"
    return "'" + text + "'"


def csv(values):
    return ",".join(values) if values else None


def number(value):
    return value if value is not None else "NULL"


def sql_lines(entries):
    """The statements, one per line, without line terminators."""
    yield f"-- Generated by tools/restore_entries.py from an export of GET /api/entries; {len(entries)} rows"
    yield "BEGIN;"
    yield "DELETE FROM entry;"
    for e in sorted(entries, key=lambda x: x["id"]):
        poster_path = e["posterUrl"][e["posterUrl"].rfind("/"):] if e.get("posterUrl") else None
        values = [
            e["id"], e["tmdbId"], lit(e["mediaType"]), lit(e["category"]), lit(e["title"]),
            lit(e.get("originalTitle")), number(e.get("releaseYear")), lit(csv(e.get("countries"))),
            lit(csv(str(g) for g in e.get("genreIds") or [])), lit(csv(e.get("cast"))), lit(e.get("overview")),
            lit(poster_path), number(e.get("tmdbRating")), number(e.get("myRating")), lit(e.get("review")),
            lit(e.get("titleBe")), lit(e.get("overviewBe")), lit(e["createdAt"]),
        ]
        yield f"INSERT INTO entry ({COLUMNS}) VALUES ({', '.join(str(v) for v in values)});"
    yield "SELECT setval(pg_get_serial_sequence('entry', 'id'), (SELECT max(id) FROM entry));"
    yield "COMMIT;"


def main(argv):
    if len(argv) not in (2, 3):
        print("usage: python restore_entries.py entries.json [restore.sql]", file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as source:
        entries = json.load(source)
    text = NEWLINE.join(sql_lines(entries)) + NEWLINE
    if len(argv) == 3:
        # Bytes written here, not text handed to a shell: no console code page, BOM or CRLF gets in
        with open(argv[2], "w", encoding="utf-8", newline=NEWLINE) as target:
            target.write(text)
    else:
        sys.stdout.reconfigure(encoding="utf-8", newline=NEWLINE)
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
