#!/usr/bin/env python3
"""Turns an export of GET /api/entries into SQL that recreates the entry table's contents elsewhere.

Usage: python restore_entries.py entries.json > restore.sql
       psql -v ON_ERROR_STOP=1 -f restore.sql "<connection string>"
       (after the application has run its migrations there; keep the options before the connection string,
        the Windows build of psql ignores anything that follows it)

The SQL replaces every row, keeps the original ids and timestamps, and resets the id sequence. Used when the
list moves to another database: the migrations recreate the schema and the seed, this brings the owner's
additions, ratings, feedback and Belarusian text.
"""
import json
import sys

NEWLINE = chr(10)
CR = chr(13)
BACKSLASH = chr(92)


def lit(value):
    """SQL literal; text with line breaks or backslashes becomes an E-string, so that the file stays one
    statement per line and no CRLF conversion (Windows console, git, editors) can alter the stored text."""
    if value is None:
        return "NULL"
    text = str(value).replace("'", "''")
    if NEWLINE in text or CR in text or BACKSLASH in text:
        text = text.replace(BACKSLASH, BACKSLASH * 2).replace(CR, "").replace(NEWLINE, BACKSLASH + "n")
        return "E'" + text + "'"
    return "'" + text + "'"


def csv(values):
    return ",".join(values) if values else None


sys.stdout.reconfigure(newline=NEWLINE)  # never let the console turn line endings into CRLF
entries = json.load(open(sys.argv[1], encoding="utf-8"))
columns = ("id, tmdb_id, media_type, category, title, original_title, release_year, countries, genre_ids, "
           "cast_names, overview, poster_path, tmdb_rating, my_rating, review, title_be, overview_be, created_at")
print("-- Generated by tools/restore_entries.py from an export of GET /api/entries;", len(entries), "rows")
print("BEGIN;")
print("DELETE FROM entry;")
for e in sorted(entries, key=lambda x: x["id"]):
    poster_path = e["posterUrl"][e["posterUrl"].rfind("/"):] if e.get("posterUrl") else None
    values = [
        e["id"], e["tmdbId"], lit(e["mediaType"]), lit(e["category"]), lit(e["title"]), lit(e.get("originalTitle")),
        e.get("releaseYear") if e.get("releaseYear") is not None else "NULL",
        lit(csv(e.get("countries"))), lit(csv(str(g) for g in e.get("genreIds") or [])), lit(csv(e.get("cast"))),
        lit(e.get("overview")), lit(poster_path),
        e["tmdbRating"] if e.get("tmdbRating") is not None else "NULL",
        e["myRating"] if e.get("myRating") is not None else "NULL",
        lit(e.get("review")), lit(e.get("titleBe")), lit(e.get("overviewBe")), lit(e["createdAt"]),
    ]
    print(f"INSERT INTO entry ({columns}) VALUES ({', '.join(str(v) for v in values)});")
print("SELECT setval(pg_get_serial_sequence('entry', 'id'), (SELECT max(id) FROM entry));")
print("COMMIT;")
